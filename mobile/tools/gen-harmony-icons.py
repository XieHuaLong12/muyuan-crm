#!/usr/bin/env python3
"""
Converts Lucide icons into single absolute SVG path strings for ArkUI `Path().commands(...)`.

    pip install svgelements==1.9.6
    npm pack lucide-static@0.468.0 && tar xzf lucide-static-0.468.0.tgz
    python3 mobile/tools/gen-harmony-icons.py package/icons

Lucide 0.468.0 is the same version the PC BOS uses (lucide-react). Circles, rectangles, lines and polylines are turned
into path data (arcs approximated by cubic curves) so one stroked Path draws the whole icon on a 24×24 grid that
LvIcon scales to the icon size (see components/LvIcon.ets).
Output: mobile/harmony/entry/src/main/ets/components/IconData.ets (generated — edit the NAMES list, not the output).
"""
import os
import re
import sys
from svgelements import SVG, Shape, Path

NAMES = [
    'layout-dashboard', 'users', 'package', 'message-circle', 'user-round', 'bell', 'search', 'plus', 'chevron-left',
    'chevron-right', 'chevron-down', 'phone', 'mail', 'map-pin', 'clock', 'alarm-clock', 'timer', 'calendar-clock',
    'check', 'check-check', 'x', 'ellipsis', 'trending-up', 'trending-down', 'file-text', 'receipt', 'truck', 'factory',
    'credit-card', 'hand-coins', 'banknote', 'shield-check', 'key-round', 'log-out', 'info', 'settings',
    'triangle-alert', 'circle-alert', 'megaphone', 'inbox', 'sparkles', 'send', 'refresh-cw', 'eye', 'eye-off',
    'smartphone', 'list-todo', 'circle-check', 'pencil', 'copy', 'external-link', 'user-plus', 'user-round-plus',
    'user-check', 'wifi-off', 'rotate-ccw', 'history', 'flag', 'languages', 'cloud-download', 'server', 'globe',
    'image', 'mic', 'target',
]

def icon_path(file):
    svg = SVG.parse(file, reify=True)
    parts = []
    for element in svg.elements():
        if isinstance(element, Shape) and not isinstance(element, SVG):
            # Absolute commands: the parts are joined into one path, so a relative move would start from the
            # previous part's end point. Spaces only (no commas) keep the plainest form of the SVG path grammar.
            # Arcs become cubic curves so every number is a coordinate: LvIcon scales the whole string by one factor
            # (24-unit viewport → icon size in px) without touching arc radii, rotations or flags.
            path = Path(element)
            path.approximate_arcs_with_cubics()
            d = path.d(relative=False).replace(',', ' ')
            d = re.sub(r'-?\d*\.\d+', lambda m: f'{float(m.group()):.3f}'.rstrip('0').rstrip('.'), d)
            if d:
                parts.append(d)
    return ' '.join(parts)

def main():
    src = sys.argv[1] if len(sys.argv) > 1 else 'package/icons'
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'harmony', 'entry', 'src', 'main', 'ets', 'components')
    lines = [
        '// Generated by mobile/tools/gen-harmony-icons.py from Lucide 0.468.0 (ISC License, https://lucide.dev).',
        '// Do not edit by hand. Each value is absolute SVG path data on a 24×24 grid (M/L/C/S/Z only), scaled and stroked by LvIcon.',
        'export const ICON_PATHS: Record<string, string> = {',
    ]
    for name in NAMES:
        d = icon_path(os.path.join(src, f'{name}.svg'))
        lines.append(f"  '{name}': '{d}',")
    lines.append('};')
    lines.append('')
    out = os.path.join(root, 'IconData.ets')
    os.makedirs(root, exist_ok=True)
    with open(out, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(lines))
    print(f'wrote {os.path.normpath(out)} ({len(NAMES)} icons)')

if __name__ == '__main__':
    main()
