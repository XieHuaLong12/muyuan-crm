import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { db } from '../lib/db';
import { token,sessionUser } from '../lib/auth';
import { dayKey } from '../lib/time';
import { createUserAccount,salesAccounts,updateSalesAccount } from '../services/sales-account-service';
import { saveCustomer,addFollowUp,addDeal } from '../services/customer-service';
import { createTask,listTasks,updateTask } from '../services/task-service';
import { actionCenter,taskInsight,completeTask } from '../services/action-center-service';
import { salesQueue } from '../services/bos-sales-service';
import { salesPerformance,saveSalesTarget,saveFirstContactPolicy,firstContactFocus } from '../services/sales-team-service';
import { syncCustomerWorkflow,getReminders } from '../services/workflow-service';
import { deleteTestCustomers } from './identity-test-cleanup';
import { identityChain } from '../services/identity-chain-service';

test('two sales, transferred customers, first contact, performance targets and revoked sessions stay isolated',async()=>{
  const adminRow=await db.user.findUniqueOrThrow({where:{email:'admin@example.com'}}),admin={id:adminRow.id,name:adminRow.name,email:adminRow.email,role:'ADMIN'};
  const tag=randomUUID(),ids:string[]=[],customers:string[]=[];
  const originalPolicy=await db.setting.findUniqueOrThrow({where:{id:'system'}});
  try{
    const a=await createUserAccount({name:'Role sales A',email:`role-a-${tag}@example.test`,password:'role-test-password'},admin);ids.push(a.id);
    const b=await createUserAccount({name:'Role sales B',email:`role-b-${tag}@example.test`,password:'role-test-password'},admin);ids.push(b.id);
    const actorA={id:a.id,name:a.name,email:a.email,role:a.role},actorB={id:b.id,name:b.name,email:b.email,role:b.role};
    await assert.rejects(createUserAccount({name:'Blocked',email:'blocked@example.test',password:'role-test-password'},actorA),{status:403});
    await assert.rejects(salesAccounts(actorA),{status:403});
    await saveFirstContactPolicy({hours:4},admin);
    const c=await saveCustomer({name:`Scope needle ${tag}`,ownerId:a.id},admin);customers.push(c.id);
    const outside=await saveCustomer({name:`Scope needle other ${tag}`,ownerId:b.id},admin);customers.push(outside.id);
    const deadline=await db.customer.findUniqueOrThrow({where:{id:c.id}});
    assert.ok(deadline.assignedAt&&deadline.firstContactDueAt);assert.equal(deadline.firstContactDueAt.getTime()-deadline.assignedAt.getTime(),4*3600000);
    assert.equal(await db.task.count({where:{customerId:c.id,automationKey:{startsWith:'first-contact:'},status:'TODO'}}),1);
    await syncCustomerWorkflow(c.id);await syncCustomerWorkflow(c.id);
    assert.equal(await db.task.count({where:{customerId:c.id,automationKey:{startsWith:'first-contact:'},status:'TODO'}}),1);
    assert.ok((await salesQueue(actorA,{queue:'new'})).customers.some(row=>row.id===c.id));
    assert.ok((await salesQueue(actorA,{queue:'today'})).customers.some(row=>row.id===c.id));
    const personal=await createTask({title:'Scope needle personal',dueDate:new Date().toISOString()},actorA);
    const linked=await createTask({customerId:c.id,title:'Scope needle linked',dueDate:new Date().toISOString()},actorA);
    await db.whatsAppMessage.create({data:{customerId:c.id,content:'Administrator supervision only',source:'whatsapp_web',direction:'INBOUND',status:'RECEIVED',raw:'{}',sentAt:new Date()}});
    const personalInsight=await taskInsight(actorA,linked.id);
    assert.deepEqual(personalInsight.customer?.whatsappMessages,[]);assert.ok(!personalInsight.timeline.some(item=>item.kind==='WHATSAPP'));
    assert.equal((await taskInsight(admin,linked.id)).customer?.whatsappMessages[0].content,'Administrator supervision only');
    assert.deepEqual((await identityChain({customerId:c.id},actorA)).messages,[]);
    assert.equal((await identityChain({customerId:c.id},admin)).messages[0].content,'Administrator supervision only');
    const outsider=await createTask({customerId:outside.id,title:'Scope needle outsider',dueDate:new Date().toISOString()},actorB);
    const searched=await actionCenter(actorA,{view:'ALL',q:'Scope needle'});
    assert.ok(searched.tasks.some(t=>t.id===linked.id));assert.ok(searched.tasks.some(t=>t.id===personal.id));assert.ok(!searched.tasks.some(t=>t.id===outsider.id));
    await saveCustomer({name:c.name,ownerId:b.id},admin,c.id);
    assert.ok(!(await actionCenter(actorA,{view:'ALL',q:'Scope needle'})).tasks.some(t=>t.id===linked.id));
    assert.ok(!(await listTasks(actorA,{status:'ALL'})).tasks.some(t=>t.id===linked.id));
    await assert.rejects(taskInsight(actorA,linked.id),{status:404});await assert.rejects(completeTask(actorA,linked.id,{}),{status:404});
    assert.ok((await listTasks(actorB,{status:'ALL'})).tasks.some(t=>t.id===linked.id));
    assert.equal(await db.customerAssignment.count({where:{customerId:c.id}}),2);
    const first=await db.task.findFirstOrThrow({where:{customerId:c.id,status:'TODO',automationKey:{startsWith:'first-contact:'}}});
    await updateTask(first.id,{status:'DONE'},actorB);
    assert.ok((await db.customer.findUniqueOrThrow({where:{id:c.id}})).firstContactAt);
    assert.ok(!(await salesQueue(actorB,{queue:'new'})).customers.some(row=>row.id===c.id));
    const fact=await saveCustomer({name:'Recorded followup',ownerId:a.id},admin);customers.push(fact.id);
    await addFollowUp(fact.id,{type:'PHONE',content:'Recorded first phone call',followUpAt:new Date().toISOString()},actorA);
    assert.equal(await db.task.count({where:{customerId:fact.id,status:{not:'DONE'},automationKey:{startsWith:'first-contact:'}}}),0);
    const month=dayKey(new Date(),originalPolicy.timezone).slice(0,7);
    await saveSalesTarget({userId:a.id,month,currency:'USD',targetRevenue:200},admin);
    await assert.rejects(saveSalesTarget({userId:a.id,month,currency:'USD',targetRevenue:300},actorA),{status:403});
    await assert.rejects(saveSalesTarget({userId:a.id,month,currency:'USD',targetRevenue:300,updatedAt:new Date(0).toISOString()},admin),{status:409});
    await addDeal(fact.id,{dealAmount:100,productCost:30,dealDate:new Date().toISOString(),currency:'USD'},actorA);
    await saveCustomer({name:fact.name,ownerId:b.id,stage:'WON'},admin,fact.id);
    const metrics=await salesPerformance(actorA,{month,currency:'USD'});
    assert.equal(metrics.rows.length,1);assert.equal(metrics.rows[0].id,a.id);assert.equal(metrics.rows[0].revenue,'100.00');assert.equal(metrics.rows[0].completion,50);
    assert.equal((await salesPerformance(actorA,{month,currency:'EUR'})).rows[0].revenue,'0.00');
    assert.equal((await salesPerformance(actorB,{month,currency:'USD'})).rows[0].revenue,'0.00');
    const expired=await saveCustomer({name:'Overdue first contact',ownerId:a.id},admin);customers.push(expired.id);
    await db.customer.update({where:{id:expired.id},data:{firstContactDueAt:new Date(Date.now()-1000)}});
    const focus=await firstContactFocus(actorA);assert.equal(focus.overdue,1);
    const generated=await db.task.findFirstOrThrow({where:{customerId:expired.id,automationKey:{startsWith:'first-contact:'}}});
    await db.task.update({where:{id:generated.id},data:{dueDate:new Date(Date.now()-1000)}});
    await db.reminder.updateMany({where:{taskId:generated.id},data:{remindAt:new Date(Date.now()-1000)}});
    assert.ok((await getReminders(actorA)).some(r=>r.taskId===generated.id));
    const oldToken=token(a.id,0);assert.ok(await sessionUser(oldToken));
    await updateSalesAccount(a.id,{action:'status',isActive:false,sessionVersion:0},admin);
    assert.equal(await sessionUser(oldToken),null);
    await assert.rejects(saveCustomer({name:'Disabled owner',ownerId:a.id},admin),{status:400});
    await assert.rejects(updateSalesAccount(a.id,{action:'status',isActive:true,sessionVersion:0},admin),{status:409});
    await updateSalesAccount(a.id,{action:'status',isActive:true,sessionVersion:1},admin);
    assert.equal(await sessionUser(oldToken),null);const renewed=token(a.id,2);assert.ok(await sessionUser(renewed));
    await updateSalesAccount(a.id,{action:'password',password:'changed-role-password',sessionVersion:2},admin);
    assert.equal(await sessionUser(renewed),null);
    assert.equal(await db.accountAudit.count({where:{subjectId:a.id,action:'PASSWORD_RESET'}}),1);
  }finally{
    await deleteTestCustomers({where:{id:{in:customers}}});
    await db.task.deleteMany({where:{createdBy:{in:ids}}});
    await db.userSalesTarget.deleteMany({where:{userId:{in:ids}}});
    await db.accountAudit.deleteMany({where:{subjectId:{in:ids}}});
    await db.user.deleteMany({where:{id:{in:ids}}});
    await db.setting.update({where:{id:'system'},data:{firstContactHours:originalPolicy.firstContactHours}});
    await db.$disconnect();
  }
});
