import { deleteTestCustomers } from './identity-test-cleanup';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdtemp,rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { db } from '../lib/db';
import { createTask,updateTask,deleteTask,listTasks } from '../services/task-service';
import { syncCustomerWorkflow,getReminders,dismissReminder,recordWorkflowEvent } from '../services/workflow-service';
import { uploadMedia,readMedia,signedMediaUrl,verifyMediaToken,mediaKind } from '../services/whatsapp-media-service';

test('media transport types match Gupshup supported types',()=>{
 assert.equal(mediaKind('image/png'),'image');assert.equal(mediaKind('image/webp'),'file');assert.equal(mediaKind('audio/mpeg'),'audio');assert.equal(mediaKind('audio/ogg'),'file');assert.equal(mediaKind('audio/ogg; codecs=opus'),'audio');
});

test('V3 tasks, reminders, scope, workflow lifecycle and media integration',async()=>{
 const admin=await db.user.findUniqueOrThrow({where:{email:'admin@example.com'}});
 const actor={id:admin.id,name:admin.name,email:admin.email,role:'ADMIN'};
 const stranger={...actor,id:'not-the-owner',role:'SALES'};
 const customer=await db.customer.create({data:{name:'V3 workflow test',ownerId:admin.id,source:'OTHER'}});
 const customerId=customer.id;
 const storage=await mkdtemp(`${tmpdir()}/crm-v3-`),oldStorage=process.env.MEDIA_STORAGE_DIR;
 process.env.MEDIA_STORAGE_DIR=storage;
 try{
  const due=new Date(Date.now()+10*60000).toISOString();
  // Concurrent tabs/webhooks must converge on one active task and two reminders.
  await db.customer.update({where:{id:customerId},data:{lastInboundAt:new Date(Date.now()-2*86400000)}});
  await Promise.all(Array.from({length:4},()=>syncCustomerWorkflow(customerId)));
  const generated=await db.task.findFirstOrThrow({where:{customerId,automationKey:{startsWith:`reply:${customerId}:`}}});
  assert.equal(await db.task.count({where:{customerId,status:'TODO'}}),1);
  assert.equal(await db.reminder.count({where:{taskId:generated.id}}),2);
  await db.customer.update({where:{id:customerId},data:{lastOutboundAt:new Date()}});
  await Promise.all([syncCustomerWorkflow(customerId),updateTask(generated.id,{status:'DONE'},actor).catch(error=>{if(!(error instanceof Error)||!error.message.includes('任务已更新'))throw error;})]);
  assert.equal((await db.task.findUniqueOrThrow({where:{id:generated.id}})).status,'DONE');
  assert.equal(await db.reminder.count({where:{taskId:generated.id,status:'PENDING'}}),0);
  await db.task.delete({where:{id:generated.id}});
  await db.customer.update({where:{id:customerId},data:{lastInboundAt:null,lastOutboundAt:null}});

  const task=await createTask({customerId,title:'Send FOB quotation',dueDate:due,reminderMinutes:30,priority:'HIGH'},actor);
  assert.equal(task.reminders.length,2);assert.equal(task.status,'TODO');
  await assert.rejects(updateTask(task.id,{status:'DONE'},stranger),/访问权限/);
  await assert.rejects(createTask({customerId,title:'Hidden',dueDate:due},stranger),/访问权限/);
  assert.equal((await listTasks(stranger,{status:'ALL'})).tasks.some(t=>t.id===task.id),false);
  assert.ok((await getReminders(actor)).some(r=>r.taskId===task.id&&r.kind==='EARLY'));
  const doing=await updateTask(task.id,{status:'DOING',updatedAt:task.updatedAt.toISOString()},actor);
  await assert.rejects(updateTask(task.id,{title:'Stale',updatedAt:new Date(0).toISOString()},actor),/已更新/);
  const done=await updateTask(task.id,{status:'DONE',updatedAt:doing.updatedAt.toISOString()},actor);
  assert.ok(done.completedAt);assert.ok(done.reminders.every(r=>r.status==='DISMISSED'));
  assert.equal((await getReminders(actor)).some(r=>r.taskId===task.id),false);
  await updateTask(task.id,{status:'TODO',dueDate:new Date(Date.now()-60000).toISOString()},actor);
  const notice=(await getReminders(actor)).find(r=>r.taskId===task.id);
  assert.equal(notice?.kind,'OVERDUE');
  await dismissReminder(notice!.id,actor);
  await deleteTask(task.id,actor);assert.equal(await db.reminder.count({where:{taskId:task.id}}),0);
  await assert.rejects(createTask({title:'Bad date',dueDate:'tomorrow'},actor));
  const inbound=new Date(Date.now()-25*3600000);
  await db.customer.update({where:{id:customerId},data:{lastInboundAt:inbound}});
  await syncCustomerWorkflow(customerId);await syncCustomerWorkflow(customerId);
  const reply=await db.task.findFirstOrThrow({where:{customerId,automationKey:{startsWith:'reply:'}}});
  assert.equal(await db.task.count({where:{customerId}}),1);
  assert.equal(reply.dueDate.getTime(),inbound.getTime()+86400000);
  assert.ok((await getReminders(actor)).some(r=>r.taskId===reply.id));
  await deleteTask(reply.id,actor);await syncCustomerWorkflow(customerId);
  assert.equal((await listTasks(actor,{customerId,status:'ALL'})).tasks.length,0);
  await db.customer.update({where:{id:customerId},data:{lastInboundAt:new Date(),lastOutboundAt:null}});
  await syncCustomerWorkflow(customerId);
  assert.equal(await db.task.count({where:{customerId,status:'TODO',deletedAt:null}}),1);
  await db.customer.update({where:{id:customerId},data:{lastOutboundAt:new Date(Date.now()+1000)}});
  await syncCustomerWorkflow(customerId);
  assert.equal(await db.task.count({where:{customerId,status:'TODO',deletedAt:null}}),0);
  const quoteAt=new Date(Date.now()-4*86400000);
  await db.customer.update({where:{id:customerId},data:{lastInboundAt:new Date(quoteAt.getTime()-1000)}});
  await db.quotation.create({data:{customerId,quoteNumber:randomUUID(),product:'Sofa',notes:'',quantity:50,unitPrice:100,currency:'USD',incoterm:'FOB',status:'SENT',sentAt:quoteAt,createdBy:actor.id}});
  await syncCustomerWorkflow(customerId);
  const followQuote=await db.task.findFirstOrThrow({where:{customerId,type:'QUOTATION'}});
  assert.equal(followQuote.dueDate.getTime(),quoteAt.getTime()+3*86400000);
  await db.customer.update({where:{id:customerId},data:{stage:'LOST'}});await syncCustomerWorkflow(customerId);
  assert.equal((await getReminders(actor)).some(r=>r.taskId===followQuote.id),false);
  await db.customer.update({where:{id:customerId},data:{stage:'CONTACTED'}});
  const event={customerId,requestId:randomUUID(),kind:'SAMPLE_SENT',expectedAt:new Date(Date.now()+86400000).toISOString(),description:'Sample courier'};
  const first=await recordWorkflowEvent(event,actor),second=await recordWorkflowEvent(event,actor);
  assert.equal(first.id,second.id);assert.equal(await db.task.count({where:{customerId,type:'SAMPLE'}}),1);
  await assert.rejects(recordWorkflowEvent({...event,kind:'PAYMENT_DUE'},actor),/编号已使用/);
  await recordWorkflowEvent({...event,requestId:randomUUID(),kind:'PRODUCTION_STARTED'},actor);
  assert.equal(await db.task.count({where:{customerId,type:'PRODUCTION'}}),2);
  assert.equal(await db.task.count({where:{customerId,type:'SHIPPING'}}),1);
  const media=await uploadMedia(new File(['catalog'],'catalog.pdf',{type:'application/pdf'}),customerId,actor);
  assert.equal((await readMedia(media.id)).buffer.toString(),'catalog');
  await assert.rejects(uploadMedia(new File(['x'],'x.html',{type:'text/html'}),customerId,actor),/支持/);
  await assert.rejects(uploadMedia(new File(['x'],'x.pdf',{type:'application/pdf'}),customerId,stranger),/访问权限/);
  const url=new URL(signedMediaUrl(media.id,'https://crm.example.com'));
  assert.ok(verifyMediaToken(media.id,url.searchParams.get('expires')!,url.searchParams.get('token')!));
  assert.equal(verifyMediaToken('another',url.searchParams.get('expires')!,url.searchParams.get('token')!),false);
  assert.equal(verifyMediaToken(media.id,'1',url.searchParams.get('token')!),false);
 }finally{
  await deleteTestCustomers({where:{id:customerId}});
  if(oldStorage===undefined)delete process.env.MEDIA_STORAGE_DIR;else process.env.MEDIA_STORAGE_DIR=oldStorage;
  await rm(storage,{recursive:true,force:true});await db.$disconnect();
 }
});
